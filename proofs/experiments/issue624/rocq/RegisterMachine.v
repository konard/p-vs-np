Definition tape (blocks : list Word) : list Symbol :=
  flat_map (fun w => map ofBool w ++ [separator]) blocks.
Definition home (q : nat) (blocks : list Word) : Config :=
  {| state := q; tapeLeft := []; tapeHead := blank; tapeRight := tape blocks |}.
Definition pushTime (blocks : list Word) : nat := 2 * length (tape blocks) + 4.

Theorem tape_append : forall pre post, tape (pre ++ post) = tape pre ++ tape post.
Proof. intros. unfold tape. apply flat_map_app. Qed.
Theorem tape_cons : forall w post, tape (w :: post) = map ofBool w ++ separator :: tape post.
Proof. intros. unfold tape. cbn. rewrite <- app_assoc. reflexivity. Qed.
Theorem tape_nonblank : forall blocks a, In a (tape blocks) -> a <> blank.
Proof.
  intros blocks a h. apply in_flat_map in h. destruct h as [w [_ h]].
  apply in_app_or in h. destruct h as [h|h].
  - apply in_map_iff in h. destruct h as [b [<- _]]. destruct b; discriminate.
  - simpl in h. destruct h as [<-|[]]. discriminate.
Qed.
Theorem seekRows_length : forall base slot, length (seekRows base slot) = slot.
Proof. intros base slot. revert base. induction slot; intros; simpl; auto. Qed.
Theorem seek_states : forall slot, length (program (seek slot)) = slot + 1.
Proof. intros. unfold seek. cbn. rewrite seekRows_length. lia. Qed.
Theorem push_states : forall slot b, length (program (push slot b)) = slot + 6.
Proof.
  intros. unfold push, appendMachine. cbn [program].
  rewrite length_app, length_map, seek_states. cbn [grow program length]. lia.
Qed.
Theorem seekRows_get : forall base count i, i < count ->
  nth_error (seekRows base count) i = Some
    [halt false; move (base+i) zero right; move (base+i) one right;
     move (base+i+1) separator right].
Proof.
  intros base count. revert base. induction count as [|count IH]; intros base [|i] h; try lia.
  - cbn [seekRows nth_error]. rewrite Nat.add_0_r. reflexivity.
  - cbn [seekRows nth_error]. rewrite IH by lia.
    replace (base + 1 + i) with (base + S i) by lia. reflexivity.
Qed.
Theorem seek_instruction : forall slot i, i < slot -> forall a,
  instruction (seek slot) (i+1) a =
    match a with blank => halt false | zero => move (i+1) zero right
    | one => move (i+1) one right | separator => move (i+2) separator right end.
Proof.
  intros slot i h a. unfold instruction, seek. cbn [program].
  replace (i+1) with (S i) by lia. cbn [nth_error].
  rewrite seekRows_get by lia. destruct a; cbn; f_equal; lia.
Qed.
Theorem seek_scan : forall slot off pre l tail, off + length pre <= slot ->
  Reaches (seek slot) (scanConfig (off+1) l (tape pre ++ tail)) (length (tape pre))
    (scanConfig (off+1+length pre) (rev (tape pre) ++ l) tail).
Proof.
  intros slot off pre. revert off. induction pre as [|w pre IH]; intros off l tail h.
  - unfold tape. cbn. rewrite Nat.add_0_r. apply reaches_refl.
  - assert (hi : off < slot) by (cbn in h; lia).
    assert (hs : Reaches (seek slot)
      (scanConfig (off+1) l (map ofBool w ++ separator :: (tape pre ++ tail))) (length w)
      {| state := off+1; tapeLeft := rev (map ofBool w) ++ l;
         tapeHead := separator; tapeRight := tape pre ++ tail |}).
    { rewrite <- (length_map ofBool w). apply scan_right.
      intros a ha. apply in_map_iff in ha. destruct ha as [b [<- _]].
      destruct b; apply seek_instruction; exact hi. }
    assert (hsep : step (seek slot)
      {| state := off+1; tapeLeft := rev (map ofBool w) ++ l;
         tapeHead := separator; tapeRight := tape pre ++ tail |} =
      inr (scanConfig (off+2) (separator :: (rev (map ofBool w) ++ l)) (tape pre ++ tail))).
    { unfold step. cbn [state tapeHead]. rewrite seek_instruction by exact hi.
      destruct (tape pre ++ tail); reflexivity. }
    specialize (IH (off+1) (separator :: (rev (map ofBool w) ++ l)) tail ltac:(cbn in h; lia)).
    rewrite tape_cons, length_app, length_map. cbn [length].
    rewrite rev_app_distr. cbn [rev]. repeat rewrite <- app_assoc. cbn [app].
    replace (off + 1 + S (length pre)) with (off + 1 + 1 + length pre) by lia.
    eapply reaches_trans; [exact hs|]. eapply reaches_next; [exact hsep|].
    replace (off+2) with (off+1+1) by lia. exact IH.
Qed.
Theorem seek_reaches : forall pre tail,
  Reaches (seek (length pre))
    {| state := 0; tapeLeft := []; tapeHead := blank; tapeRight := tape pre ++ tail |}
    (1+length (tape pre))
    (scanConfig (length (program (seek (length pre)))) (rev (tape pre) ++ [blank]) tail).
Proof.
  intros. rewrite seek_states.
  pose proof (seek_scan (length pre) 0 pre [blank] tail ltac:(lia)) as h.
  cbn [Nat.add] in h. rewrite Nat.add_1_r.
  replace (1+length (tape pre)) with (S (length (tape pre))) by lia.
  eapply reaches_next; [|exact h].
  destruct (tape pre ++ tail); reflexivity.
Qed.
Definition carryState (a : Symbol) : nat :=
  match a with zero => 1 | one => 2 | separator => 3 | blank => 1 end.
Theorem grow_carry_instruction : forall b a, a <> blank -> forall s,
  instruction (grow b) (carryState a) s =
    match s with blank => move 4 a stay | _ => move (carryState s) a right end.
Proof. intros b a h s. destruct a, s; try contradiction; reflexivity. Qed.
Theorem shift_reaches : forall b a xs l, a <> blank ->
  (forall s, In s xs -> s <> blank) ->
  Reaches (grow b) (scanConfig (carryState a) l xs) (length xs+1)
    (scanLeftConfig 4 [] (rev (a::xs) ++ l)).
Proof.
  intros b a xs. revert a. induction xs as [|s xs IH]; intros a l ha hx.
  - cbn [length rev app]. eapply reaches_next; [|apply reaches_refl].
    unfold step. cbn [scanConfig state tapeHead]. rewrite grow_carry_instruction by exact ha.
    reflexivity.
  - assert (hs : step (grow b) (scanConfig (carryState a) l (s::xs)) =
      inr (scanConfig (carryState s) (a::l) xs)).
    { unfold step. cbn [scanConfig state tapeHead]. rewrite grow_carry_instruction by exact ha.
      destruct s; [exfalso; apply (hx blank); [left; reflexivity|reflexivity]|..];
        destruct xs; reflexivity. }
    specialize (IH s (a::l) ltac:(apply hx; left; reflexivity)
      ltac:(intros c hc; apply hx; right; exact hc)).
    cbn [length]. eapply reaches_next; [exact hs|].
    cbn [rev]. rewrite <- app_assoc. cbn [app]. exact IH.
Qed.
Theorem grow_reaches : forall b p w r,
  (forall a, In a p -> a <> blank) -> (forall a, In a r -> a <> blank) ->
  Reaches (grow b) (scanConfig 0 (rev p ++ [blank]) (map ofBool w ++ separator :: r))
    (length p + 2*length w + 2*length r + 5)
    {| state := 5; tapeLeft := []; tapeHead := blank;
       tapeRight := p ++ map ofBool (w ++ [b]) ++ separator :: r |}.
Proof.
  intros b p w r hp hr.
  set (l := rev (map ofBool w) ++ rev p ++ [blank]).
  set (out := p ++ map ofBool (w ++ [b]) ++ separator :: r).
  assert (hs : Reaches (grow b)
    (scanConfig 0 (rev p ++ [blank]) (map ofBool w ++ separator :: r)) (length w)
    {| state := 0; tapeLeft := l; tapeHead := separator; tapeRight := r |}).
  { rewrite <- (length_map ofBool w). unfold l. apply scan_right.
    intros a ha. apply in_map_iff in ha. destruct ha as [c [<- _]]. destruct c; reflexivity. }
  assert (hi : step (grow b)
    {| state := 0; tapeLeft := l; tapeHead := separator; tapeRight := r |} =
    inr (scanConfig 3 (ofBool b :: l) r)) by (destruct r; reflexivity).
  pose proof (shift_reaches b separator r (ofBool b::l) ltac:(discriminate) hr) as hc.
  assert (he : rev (separator::r) ++ ofBool b :: l = rev out ++ [blank]).
  { unfold out, l. rewrite map_app. cbn [map rev].
    repeat rewrite rev_app_distr. cbn [rev app]. repeat rewrite <- app_assoc. reflexivity. }
  rewrite he in hc.
  assert (hout : forall a, In a out -> a <> blank).
  { intros a h. unfold out in h. repeat rewrite in_app_iff in h.
    destruct h as [h|[h|h]].
    - exact (hp a h).
    - apply in_map_iff in h. destruct h as [c [<- _]]. destruct c; discriminate.
    - destruct h as [<-|h]; [discriminate|exact (hr a h)]. }
  assert (hb : Reaches (grow b) (scanLeftConfig 4 [] (rev out ++ [blank])) (length out)
    {| state := 4; tapeLeft := []; tapeHead := blank; tapeRight := out |}).
  { pose proof (scan_left (grow b) 4 (rev out) [] [blank]) as h.
    rewrite length_rev, rev_involutive, app_nil_r in h. apply h.
    intros a ha. apply (proj2 (in_rev _ _)) in ha. specialize (hout a ha).
    destruct a; [contradiction|reflexivity|reflexivity|reflexivity]. }
  assert (hend : step (grow b)
    {| state := 4; tapeLeft := []; tapeHead := blank; tapeRight := out |} =
    inr {| state := 5; tapeLeft := []; tapeHead := blank; tapeRight := out |}) by reflexivity.
  assert (hlen : length out = length p + length w + 2 + length r).
  { unfold out. rewrite !length_app, length_map, length_app. cbn. lia. }
  replace (length p + 2*length w + 2*length r + 5) with
    (length w + S ((length r+1) + (length out + 1))) by lia.
  eapply reaches_trans; [exact hs|]. eapply reaches_next; [exact hi|].
  eapply reaches_trans; [exact hc|]. eapply reaches_trans; [exact hb|].
  eapply reaches_next; [exact hend|apply reaches_refl].
Qed.
Theorem push_reaches : forall pre post w b,
  Reaches (push (length pre) b) (home 0 (pre ++ w :: post))
    (pushTime (pre ++ w :: post))
    (home (length (program (push (length pre) b))) (pre ++ (w ++ [b]) :: post)).
Proof.
  intros.
  pose proof (reaches_append _ (grow b) _ _ _ (seek_reaches pre (map ofBool w ++ separator :: tape post))) as hs.
  pose proof (reaches_append_right (seek (length pre)) _ _ _ _
    (grow_reaches b (tape pre) w (tape post) (tape_nonblank pre) (tape_nonblank post))) as hg.
  assert (hh : forall q l xs, shiftConfig q (scanConfig 0 l xs) = scanConfig q l xs).
  { intros q l [|a xs]; reflexivity. }
  rewrite hh in hg. cbn [shiftConfig state tapeLeft tapeHead tapeRight] in hg.
  rewrite map_app in hg. cbn [map] in hg.
  unfold pushTime, home. rewrite !tape_append, !tape_cons, push_states.
  unfold push in *. rewrite seek_states in hs, hg. rewrite map_app. cbn [map].
  replace (length pre+6) with (5+(length pre+1)) by lia.
  rewrite <- app_assoc. cbn [app].
  replace (2 * length (tape pre ++ map ofBool w ++ separator :: tape post) + 4) with
    ((1+length (tape pre)) + (length (tape pre)+2*length w+2*length (tape post)+5))
    by (rewrite !length_app, length_map; cbn; lia).
  eapply reaches_trans; [exact hs|].
  unfold shiftConfig in hg. cbn [state tapeLeft tapeHead tapeRight] in hg.
  repeat rewrite <- app_assoc in hg. cbn [app] in hg.
  exact hg.
Qed.

Definition wordTime (count size : nat) : nat := count * (2*size + count + 3).
Definition emissionPolynomial : Polynomial := {| coefficient := 3; degree := 2 |}.
Theorem pushWord_states : forall slot w,
  length (program (pushWord slot w)) = (slot+6)*length w.
Proof.
  intros slot w. induction w as [|b w IH]; [cbn; lia|].
  cbn [pushWord]. unfold appendMachine. cbn [program].
  rewrite length_app, length_map, push_states, IH. cbn [length]. lia.
Qed.
Theorem wordTime_succ : forall count size,
  wordTime (count+1) size = 2*size+4 + wordTime count (size+1).
Proof. intros. unfold wordTime. nia. Qed.
Theorem pushWord_reaches : forall pre post old w,
  Reaches (pushWord (length pre) w) (home 0 (pre ++ old :: post))
    (wordTime (length w) (length (tape (pre ++ old :: post))))
    (home (length (program (pushWord (length pre) w))) (pre ++ (old ++ w) :: post)).
Proof.
  intros pre post old w. revert old. induction w as [|b w IH]; intros old.
  - rewrite app_nil_r. apply reaches_refl.
  - pose proof (reaches_append _ (pushWord (length pre) w) _ _ _ (push_reaches pre post old b)) as hp.
    pose proof (reaches_append_right (push (length pre) b) _ _ _ _ (IH (old ++ [b]))) as hw.
    assert (hf : length (program (pushWord (length pre) (b::w))) =
      length (program (pushWord (length pre) w)) + length (program (push (length pre) b))).
    { cbn [pushWord]. unfold appendMachine. cbn [program].
      rewrite length_app, length_map. lia. }
    assert (ht : wordTime (length (b::w)) (length (tape (pre ++ old::post))) =
      pushTime (pre ++ old::post) + wordTime (length w) (length (tape (pre ++ (old++[b])::post)))).
    { cbn [length]. rewrite <- Nat.add_1_r, wordTime_succ.
      unfold pushTime. rewrite !tape_append, !tape_cons, !length_app, !length_map,
        !length_app. cbn [length]. unfold wordTime. nia. }
    rewrite ht, hf. cbn [pushWord].
    eapply reaches_trans; [exact hp|].
    unfold home, shiftConfig in hw. cbn [state tapeLeft tapeHead tapeRight] in hw.
    repeat rewrite <- app_assoc in hw. cbn [app] in hw. exact hw.
Qed.
Theorem wordTime_polynomial : forall count size,
  wordTime count size <= evalPoly emissionPolynomial (size+count).
Proof. intros. unfold wordTime, emissionPolynomial, evalPoly. cbn. nia. Qed.

Record State := mkState { regs : list nat; out : Word }.
Definition regWords (values : list nat) : list Word := map (fun n => repeat true n) values.
Definition blocks (x : Word) (st : State) : list Word := x :: regWords (regs st) ++ [out st].
Definition encode (q : nat) (x : Word) (st : State) : Config := home q (blocks x st).

Theorem incr_reaches : forall x pre post value count output,
  Reaches (incr (length pre) count) (encode 0 x (mkState (pre ++ value::post) output))
    (wordTime count (length (tape (blocks x (mkState (pre ++ value::post) output)))))
    (encode (length (program (incr (length pre) count))) x
      (mkState (pre ++ (value+count)::post) output)).
Proof.
  intros. pose proof (pushWord_reaches (x::regWords pre) (regWords post++[output])
    (repeat true value) (repeat true count)) as h.
  unfold encode, blocks, incr, regWords in *. cbn [regs out length] in *.
  rewrite length_map, repeat_length, <- repeat_app in h.
  replace (S (length pre)) with (length pre+1) in h by lia.
  rewrite !map_app. cbn [map]. repeat rewrite <- app_assoc. cbn [app].
  exact h.
Qed.
Theorem emitConst_reaches : forall x st w,
  Reaches (emitConst (length (regs st)) w) (encode 0 x st)
    (wordTime (length w) (length (tape (blocks x st))))
    (encode (length (program (emitConst (length (regs st)) w))) x
      (mkState (regs st) (out st ++ w))).
Proof.
  intros. pose proof (pushWord_reaches (x::regWords (regs st)) [] (out st) w) as h.
  unfold emitConst, encode, blocks, regWords in *. cbn [regs out length] in *.
  rewrite length_map in h.
  replace (S (length (regs st))) with (length (regs st)+1) in h by lia.
  exact h.
Qed.

(** The certified straight-line subset. Further operations and loops extend
    this compiler using the same sequential embedding theorem. *)
Inductive Prog :=
| empty
| increment (slot count : nat)
| emit (w : Word)
| seq (first second : Prog).
Fixpoint WellFormed (registers : nat) (p : Prog) : Prop :=
  match p with
  | empty => True
  | increment slot _ => slot < registers
  | emit _ => True
  | seq first second => WellFormed registers first /\ WellFormed registers second
  end.
Fixpoint incrementRegs (slot count : nat) (values : list nat) : list nat :=
  match values, slot with
  | [], _ => []
  | value::rest, 0 => (value+count)::rest
  | value::rest, S slot => value::incrementRegs slot count rest
  end.
Fixpoint runProg (p : Prog) (st : State) : State :=
  match p with
  | empty => st
  | increment slot count => mkState (incrementRegs slot count (regs st)) (out st)
  | emit w => mkState (regs st) (out st ++ w)
  | seq first second => runProg second (runProg first st)
  end.
Fixpoint cost (x : Word) (p : Prog) (st : State) : nat :=
  match p with
  | empty => 0
  | increment _ count => wordTime count (length (tape (blocks x st)))
  | emit w => wordTime (length w) (length (tape (blocks x st)))
  | seq first second => cost x first st + cost x second (runProg first st)
  end.
Fixpoint compile (registers : nat) (p : Prog) : Machine :=
  match p with
  | empty => {| program := [] |}
  | increment slot count => incr slot count
  | emit w => emitConst registers w
  | seq first second => appendMachine (compile registers first) (compile registers second)
  end.

Theorem incrementRegs_length : forall slot count values,
  length (incrementRegs slot count values) = length values.
Proof.
  intros slot count values. revert slot. induction values; intros [|slot]; cbn; auto.
Qed.
Theorem incrementRegs_split : forall pre post value count,
  incrementRegs (length pre) count (pre ++ value::post) = pre ++ (value+count)::post.
Proof. induction pre; intros; cbn; [reflexivity|rewrite IHpre; reflexivity]. Qed.
Theorem register_decomposition : forall (values : list nat) slot, slot < length values ->
  exists pre value post, length pre = slot /\ values = pre ++ value::post.
Proof.
  induction values as [|value rest IH]; intros [|slot] h; cbn in h; try lia.
  - exists [], value, rest. split; reflexivity.
  - destruct (IH slot ltac:(lia)) as [pre [v [post [hp hr]]]].
    exists (value::pre), v, post. cbn. split; [lia|rewrite hr; reflexivity].
Qed.
Theorem runProg_regs_length : forall p st, length (regs (runProg p st)) = length (regs st).
Proof.
  induction p; intros; cbn [runProg regs]; try reflexivity.
  - apply incrementRegs_length.
  - rewrite IHp2, IHp1. reflexivity.
Qed.
Theorem increment_state_reaches : forall x st slot count, slot < length (regs st) ->
  Reaches (incr slot count) (encode 0 x st)
    (wordTime count (length (tape (blocks x st))))
    (encode (length (program (incr slot count))) x (runProg (increment slot count) st)).
Proof.
  intros x [values output] slot count h. cbn [regs] in h.
  destruct (register_decomposition values slot h) as [pre [value [post [hp hv]]]].
  subst values slot. cbn [runProg regs out]. rewrite incrementRegs_split.
  apply incr_reaches.
Qed.
Theorem compile_reaches : forall x k p st, WellFormed k p -> length (regs st) = k ->
  Reaches (compile k p) (encode 0 x st) (cost x p st)
    (encode (length (program (compile k p))) x (runProg p st)).
Proof.
  intros x k p. induction p; intros st hp hs.
  - apply reaches_refl.
  - cbn [compile cost runProg]. apply increment_state_reaches. cbn in hp. lia.
  - cbn [compile cost runProg]. rewrite <- hs. apply emitConst_reaches.
  - destruct hp as [hf hg]. cbn [compile cost runProg].
    pose proof (reaches_append _ (compile k p2) _ _ _ (IHp1 st hf hs)) as ha.
    assert (hs' : length (regs (runProg p1 st)) = k) by (rewrite runProg_regs_length; exact hs).
    pose proof (reaches_append_right (compile k p1) _ _ _ _
      (IHp2 (runProg p1 st) hg hs')) as hb.
    unfold encode, home, shiftConfig in hb. cbn [state tapeLeft tapeHead tapeRight] in hb.
    cbn [Nat.add] in hb. unfold appendMachine. cbn [program].
    rewrite length_app, length_map.
    rewrite (Nat.add_comm (length (program (compile k p1))) (length (program (compile k p2)))).
    eapply reaches_trans; [exact ha|exact hb].
Qed.

Fixpoint growth (p : Prog) : nat :=
  match p with
  | empty => 0
  | increment _ count => count
  | emit w => length w
  | seq first second => growth first + growth second
  end.
Theorem tape_regWords_length : forall values,
  length (tape (regWords values)) = list_sum values + length values.
Proof.
  induction values; [reflexivity|].
  unfold regWords in *. cbn [map]. rewrite tape_cons, length_app, length_map, repeat_length.
  cbn [length]. rewrite IHvalues. unfold list_sum. cbn [fold_right]. lia.
Qed.
Theorem blocks_length : forall x st,
  length (tape (blocks x st)) = length x + list_sum (regs st) + length (regs st) + length (out st) + 2.
Proof.
  intros. unfold blocks. rewrite tape_cons, tape_append, tape_cons, length_app, length_map.
  cbn [length]. rewrite !length_app, tape_regWords_length, length_map.
  cbn [tape flat_map length]. lia.
Qed.
Theorem incrementRegs_sum : forall slot count values, slot < length values ->
  list_sum (incrementRegs slot count values) = list_sum values + count.
Proof.
  intros slot count values. revert slot. induction values; intros [|slot] h;
    unfold list_sum in *; cbn [incrementRegs fold_right length] in *; try lia.
  rewrite IHvalues by lia. lia.
Qed.
Theorem runProg_tape_length : forall x k p st, WellFormed k p -> length (regs st) = k ->
  length (tape (blocks x (runProg p st))) = length (tape (blocks x st)) + growth p.
Proof.
  intros x k p. induction p; intros st hp hs.
  - cbn [runProg growth]. lia.
  - rewrite !blocks_length. cbn [runProg growth regs out].
    rewrite incrementRegs_length, incrementRegs_sum by (cbn in hp; lia). lia.
  - rewrite !blocks_length. cbn [runProg growth regs out]. rewrite length_app. lia.
  - destruct hp as [hf hg]. cbn [runProg growth].
    rewrite (IHp2 (runProg p1 st) hg) by (rewrite runProg_regs_length; exact hs).
    rewrite IHp1 by assumption. lia.
Qed.
Theorem wordTime_add : forall first second size,
  wordTime (first+second) size = wordTime first size + wordTime second (size+first).
Proof. intros. unfold wordTime. nia. Qed.
Theorem cost_eq_wordTime : forall x k p st, WellFormed k p -> length (regs st) = k ->
  cost x p st = wordTime (growth p) (length (tape (blocks x st))).
Proof.
  intros x k p. induction p; intros st hp hs; try reflexivity.
  destruct hp as [hf hg]. cbn [cost growth].
  rewrite (IHp1 st hf hs), (IHp2 (runProg p1 st) hg) by (rewrite runProg_regs_length; exact hs).
  rewrite (runProg_tape_length x k p1 st hf hs), wordTime_add. reflexivity.
Qed.
Theorem cost_polynomial : forall x k p st, WellFormed k p -> length (regs st) = k ->
  cost x p st <= evalPoly emissionPolynomial (length (tape (blocks x st)) + growth p).
Proof. intros. rewrite (cost_eq_wordTime x k p st H H0). apply wordTime_polynomial. Qed.

